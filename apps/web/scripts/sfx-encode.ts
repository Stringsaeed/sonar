// Encodes the picked take of each cue (sfx/picks.json, default take 1) for the web:
// loudness-normalized, leading silence trimmed, short fade-out, as Opus .webm plus AAC .m4a
// fallback in public/sfx. Then regenerates src/lib/sound/available.gen.ts.
//
//   node scripts/sfx-encode.ts
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const web = join(import.meta.dirname, "..");
const sfx = join(web, "sfx");
const out = join(web, "public", "sfx");
const prompts: Record<string, { loop?: boolean }> = JSON.parse(
  readFileSync(join(sfx, "prompts.json"), "utf8"),
);
const picks: Record<string, number> = JSON.parse(readFileSync(join(sfx, "picks.json"), "utf8"));

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const encoded: string[] = [];
for (const [cue, spec] of Object.entries(prompts)) {
  const source = join(sfx, "takes", cue, `${picks[cue] ?? 1}.mp3`);
  if (!existsSync(source)) continue;

  // Loops keep their full length and edges so they stay seamless.
  const filters = spec.loop
    ? ["loudnorm=I=-24:TP=-2:LRA=7"]
    : [
        "silenceremove=start_periods=1:start_threshold=-55dB",
        "loudnorm=I=-16:TP=-1.5:LRA=11",
        "areverse,afade=t=in:d=0.04,areverse",
      ];
  const common = [
    "-hide_banner",
    "-loglevel",
    "error",
    "-y",
    "-i",
    source,
    "-af",
    filters.join(","),
    // Same input, same bytes: keeps re-encodes from churning git.
    "-map_metadata",
    "-1",
    "-fflags",
    "+bitexact",
    "-flags:a",
    "+bitexact",
  ];
  // Effects are mono (smaller, and they're centred anyway); the ambient bed keeps its stereo.
  const channels = spec.loop ? ["-ac", "2"] : ["-ac", "1"];

  execFileSync("ffmpeg", [
    ...common,
    ...channels,
    "-c:a",
    "libopus",
    "-b:a",
    spec.loop ? "64k" : "48k",
    join(out, `${cue}.webm`),
  ]);
  execFileSync("ffmpeg", [
    ...common,
    ...channels,
    "-c:a",
    "aac",
    "-b:a",
    spec.loop ? "96k" : "80k",
    join(out, `${cue}.m4a`),
  ]);
  encoded.push(cue);
  console.log(`encoded ${cue} (take ${picks[cue] ?? 1})`);
}

writeFileSync(
  join(web, "src", "lib", "sound", "available.gen.ts"),
  `// Generated by \`vp run @sonar/web#sfx:encode\` — the cues that have encoded files in public/sfx.
import type { Cue } from "./cues.ts";

export const AVAILABLE_CUES: ReadonlyArray<Cue> = ${JSON.stringify(encoded)};
`,
);
